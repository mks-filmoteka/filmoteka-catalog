    ADD COLUMN person_id BIGINT,
    ADD COLUMN position INT;

UPDATE film_actor fa
SET person_id = linked.person_id,
    position  = linked.position
FROM (SELECT fa.ctid AS row_id,
             p.id AS person_id,
             ROW_NUMBER() OVER (PARTITION BY fa.film_id ORDER BY fa.ctid) - 1 AS position
      FROM film_actor fa
               JOIN actor a ON a.id = fa.actor_id
               JOIN person p ON p.name = a.name) linked
WHERE fa.ctid = linked.row_id;

ALTER TABLE film_actor
    DROP COLUMN actor_id,
    ALTER COLUMN person_id SET NOT NULL,
    ALTER COLUMN position SET NOT NULL,
    ADD PRIMARY KEY (film_id, position),
    ADD CONSTRAINT film_actor_person_fk FOREIGN KEY (person_id) REFERENCES person (id);

CREATE INDEX idx_film_actor_person_id ON film_actor (person_id);

ALTER TABLE film_director
    ADD COLUMN person_id BIGINT,
    ADD COLUMN position INT;

UPDATE film_director fd
SET person_id = linked.person_id,
    position  = linked.position
FROM (SELECT fd.ctid AS row_id,
             p.id AS person_id,
             ROW_NUMBER() OVER (PARTITION BY fd.film_id ORDER BY fd.ctid) - 1 AS position
      FROM film_director fd
               JOIN director d ON d.id = fd.director_id
               JOIN person p ON p.name = d.name) linked
WHERE fd.ctid = linked.row_id;

ALTER TABLE film_director
    DROP COLUMN director_id,
    ALTER COLUMN person_id SET NOT NULL,
    ALTER COLUMN position SET NOT NULL,
    ADD PRIMARY KEY (film_id, position),
