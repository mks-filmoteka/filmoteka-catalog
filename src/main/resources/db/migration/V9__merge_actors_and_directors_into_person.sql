CREATE TABLE person
(
    id              BIGINT          GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            VARCHAR(100)    NOT NULL,
    birth_date      DATE,
    death_date      DATE,
    place_of_birth  VARCHAR(255),
    photo_name      VARCHAR(1000),
    created_ts      TIMESTAMP       NOT NULL    DEFAULT CURRENT_TIMESTAMP,
    updated_ts      TIMESTAMP       NOT NULL    DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_person_name UNIQUE (name)
);

INSERT INTO person (name, created_ts, updated_ts)
SELECT name, MIN(created_ts), MAX(updated_ts)
FROM (SELECT name, created_ts, updated_ts FROM actor
      UNION ALL
      SELECT name, created_ts, updated_ts FROM director) people
GROUP BY name;

